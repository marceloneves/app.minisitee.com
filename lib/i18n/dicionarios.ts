export function traduzir(d: Dicionario, chave: keyof Dicionario, vars?: Record<string, string | number>) {
  let texto: string = d[chave]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      texto = texto.replaceAll(`{${k}}`, String(v))
    }
  }
  return texto
}

